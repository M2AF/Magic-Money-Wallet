#!/usr/bin/env node
/**
 * build-swap-core.mjs — generate the shared swap core bundle for ChainLens.
 *
 *   node scripts/build-swap-core.mjs [outDir]          write swap-core.js + manifest
 *   node scripts/build-swap-core.mjs [outDir] --check  exit 1 if outDir is stale
 *
 * outDir defaults to ../chainlens/public (the sibling ChainLens checkout).
 *
 * The bundle is src/shared/swap-core-browser.ts and everything it imports, as a
 * dependency-free IIFE: a classic <script> gets `MagicMoneySwapCore` as a global,
 * and Node's require() gets it as module.exports (ChainLens's backend uses it to
 * filter quote candidates). The manifest records the SHA-256 of every bundled
 * source and of the bundle itself, so either repo can detect drift:
 *   - here: `--check` (and a vitest) regenerate and compare;
 *   - in ChainLens: a node test recomputes the bundle hash against the manifest,
 *     so a hand edit to the generated file fails CI.
 */
import { build, version as esbuildVersion } from 'esbuild'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = 'src/shared/swap-core-browser.ts'
const BUNDLE = 'swap-core.js'
const MANIFEST = 'swap-core.manifest.json'

const sha256 = (data) => createHash('sha256').update(data).digest('hex')
const posix = (p) => p.split('\\').join('/')

export async function generateSwapCore() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    globalName: 'MagicMoneySwapCore',
    platform: 'neutral',
    target: 'es2020',
    write: false,
    metafile: true,
    legalComments: 'none',
    charset: 'utf8',
    footer: {
      js: "if (typeof module === 'object' && module.exports) module.exports = MagicMoneySwapCore;",
    },
  })
  const sources = {}
  for (const input of Object.keys(result.metafile.inputs).sort()) {
    sources[posix(input)] = sha256(readFileSync(join(root, input)))
  }
  const header = [
    '/*',
    ' * swap-core.js — GENERATED by Magic Money Wallet scripts/build-swap-core.mjs. Do not edit.',
    ` * Entry: ${ENTRY}. Source hashes: ${MANIFEST}.`,
    ' * Regenerate there with `npm run build:swap-core`; the drift tests in both repos fail otherwise.',
    ' */',
    '',
  ].join('\n')
  const bundle = header + result.outputFiles[0].text
  const manifest = {
    generator: 'magicmoney-wallet/scripts/build-swap-core.mjs',
    entry: ENTRY,
    esbuildVersion,
    sources,
    bundleSha256: sha256(bundle),
  }
  return { bundle, manifest }
}

async function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const outDir = resolve(root, args.find(a => !a.startsWith('--')) ?? '../chainlens/public')
  const { bundle, manifest } = await generateSwapCore()
  const bundlePath = join(outDir, BUNDLE)
  const manifestPath = join(outDir, MANIFEST)

  if (check) {
    const stale = []
    if (!existsSync(bundlePath) || readFileSync(bundlePath, 'utf8') !== bundle) stale.push(BUNDLE)
    const current = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : null
    if (!current || JSON.stringify(current.sources) !== JSON.stringify(manifest.sources)) stale.push(MANIFEST)
    if (stale.length) {
      console.error(`Stale in ${relative(root, outDir)}: ${stale.join(', ')}. Run npm run build:swap-core.`)
      process.exit(1)
    }
    console.log(`swap core is current in ${relative(root, outDir)} (${Object.keys(manifest.sources).length} sources)`)
    return
  }
  mkdirSync(outDir, { recursive: true })
  writeFileSync(bundlePath, bundle)
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
  console.log(`wrote ${relative(root, bundlePath)} (${bundle.length} bytes, ${Object.keys(manifest.sources).length} sources)`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(err => { console.error(err); process.exit(1) })
}
